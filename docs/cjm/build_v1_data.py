boards = []

def board(id, title, subtitle, x, y, width=2450, height=1800):
    b = dict(id=id, title=title, subtitle=subtitle, x=x, y=y, width=width,
             height=height, nodes=[], edges=[], notes=[])
    boards.append(b)
    return b

def node(b,id,x,y,title,body,refs='',w=340,h=230,kind='job',hyp=False,**meta):
    n=dict(id=id,x=x,y=y,w=w,h=h,title=title,body=body,refs=refs,kind=kind,hypothesis=hyp,meta=meta)
    b['nodes'].append(n)
    return n

def note(b,x,y,text,width=2250,size=20):
    b['notes'].append(dict(x=x,y=y,text=text,width=width,size=size))

def edge(b,a,z,points=None,label=None,labelX=None,labelY=None,ret=False):
    ns={n['id']:n for n in b['nodes']}; p=ns[a];q=ns[z]
    if points is None:
        if p['y']==q['y']:
            points=[[p['x']+p['w'],p['y']+p['h']/2],[q['x'],q['y']+q['h']/2]]
        elif p['x']==q['x']:
            if p['y']<q['y']:
                points=[[p['x']+p['w']/2,p['y']+p['h']],[q['x']+q['w']/2,q['y']]]
            else:
                points=[[p['x']+p['w']/2,p['y']],[q['x']+q['w']/2,q['y']+q['h']]]
        else:
            raise ValueError(f'explicit route required {a} {z}')
    e=dict(id=f'{b["id"]}-e{len(b["edges"])+1}',source=a,target=z,points=points,returning=ret)
    if label:e.update(label=label,labelX=labelX,labelY=labelY,labelWidth=310)
    b['edges'].append(e)

def chain(b,*ids):
    for a,z in zip(ids,ids[1:]):edge(b,a,z)

