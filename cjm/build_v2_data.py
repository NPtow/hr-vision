def board(id, title, subtitle, y, width=5000, height=3320, x=0):
    b = dict(id=id, title=title, subtitle=subtitle, x=x, y=y, width=width,
             height=height, nodes=[], edges=[], notes=[], contours=[])
    BOARDS.append(b)
    return b


def note(b, x, y, text, width=4600, size=20):
    b['notes'].append(dict(x=x, y=y, text=text, width=width, size=size))


def node(b, id, x, y, title, body, refs='', w=420, h=240, kind='job', **meta):
    n = dict(id=id, x=x, y=y, w=w, h=h, title=title, body=body, refs=refs,
             kind=kind, meta=meta)
    b['nodes'].append(n)
    return n


def edge(b, a, z, points=None, label=None, lx=None, ly=None, ret=False):
    ns = {n['id']: n for n in b['nodes']}
    p, q = ns[a], ns[z]
    if points is None:
        if p['y'] == q['y']:
            points = [[p['x'] + p['w'], p['y'] + p['h']/2], [q['x'], q['y'] + q['h']/2]]
        elif p['x'] == q['x']:
            if p['y'] < q['y']:
                points = [[p['x'] + p['w']/2, p['y'] + p['h']], [p['x'] + p['w']/2, q['y']]]
            else:
                points = [[p['x'] + p['w']/2, p['y']], [p['x'] + p['w']/2, q['y'] + q['h']]]
        else:
            raise ValueError(f'Explicit route needed: {a} → {z}')
    e = dict(id=f'e{len(b["edges"])+1}', source=a, target=z, points=points, returning=ret)
    if label:
        e.update(label=label, labelX=lx, labelY=ly, labelWidth=360)
    b['edges'].append(e)


def chain(b, *ids):
    for a, z in zip(ids, ids[1:]):
        edge(b, a, z)


def cell(title, body, screen=None, modules='', external=False):
    return dict(title=title, body=body, screen=screen,
                modules=modules.split(), external=external)


def rows(b, strategy, data, labels):
    b['strategy'] = strategy
    b['columns'] = [dict(x=x, label=f'{i+1:02}  {p}', width=440) for i, (x,p) in enumerate(zip(X,PHASES))]
    b['lanes'] = [dict(label=label, y=y-140, width=4820) for label,y in zip(labels,Y)]
    groups = []
    for ri, role in enumerate(ROLES):
        current = None
        for ci, c in enumerate(data[role]):
            nid = f'{ROW[role]}{ci}'
            if c is None:
                current = None
                continue
            refs = ('Внешний шаг' if c['external'] else 'Блоки: ' + ' · '.join(c['modules']))
            n = node(b,nid,X[ci],Y[ri],c['title'],c['body'],refs,
                     kind='external' if c['external'] else 'job',role=role,
                     screen=c['screen'],modules=c['modules'],phase=ci,
                     before='Предыдущая работа / вход в сценарий' if ci==0 else f'{ROW[role]}{ci-1}',
                     evidence='cjm/v2-основания.md; cjm/research/*.md; sources',
                     readiness='Не проверена; проектируемое покрытие')
            if c['screen']:
                sid=c['screen']
                if sid not in SCREENS:
                    raise ValueError(sid)
                if current and current['screenId']==sid:
                    current['nodes'].append(nid)
                else:
                    current=dict(id=f'{ROW[role]}-{ci}-{sid}', screenId=sid,
                                 label=SCREENS[sid]['name'], nodes=[nid])
                    groups.append(current)
            else:
                current=None
        ids=[f'{ROW[role]}{i}' for i,c in enumerate(data[role]) if c]
        for a,z in zip(ids, ids[1:]):
            if int(z[1:]) == int(a[1:])+1 and not (strategy == 'ats' and role == 'agency'):
                edge(b,a,z)
    b['contours']=groups
    note(b,220,1920,'Обводка = экран участника. B01…B27 = общие функциональные блоки. E/H = представления кабинета компании; A = наша команда; C = кандидат.',4600,20)
    note(b,220,1960,'Колонки задают общую логику, а не синхронные сроки. Первые кандидаты идут дальше, пока продолжаются поиск и проверки остальных.',4600,20)


