"""Real legacy SQLite migration; no provider calls or application data outside fixtures."""
import json
from pathlib import Path
import sqlite3
import tempfile
import unittest

import candidate_invites
from candidate_portal import CandidatePortal, migrate_search
import employer_store
import employer_workflow


STAMP = '2026-10-13T10:00:00Z'
DEPENDENTS = (
    'cp_meetings', 'em_reviews', 'cp_employer_workflows', 'cp_meeting_feedback',
    'cp_offer_versions', 'cp_workflow_messages', 'cp_workflow_commands',
    'cp_workflow_events', 'em_meeting_transcripts',
)


class CandidateSearchMigrationTest(unittest.TestCase):
    def setUp(self):
        self.directory = tempfile.TemporaryDirectory(prefix='hr-search-migration-')
        self.addCleanup(self.directory.cleanup)
        self.path = Path(self.directory.name) / 'legacy.sqlite3'
        self.db = sqlite3.connect(self.path)
        self.addCleanup(self.db.close)
        self.db.execute('PRAGMA foreign_keys=ON')
        # Six candidate columns and seven application columns, including the
        # old permanent candidate/vacancy uniqueness constraint. These are not
        # generated by the new initializer, which would skip the migration.
        self.db.executescript('''
            CREATE TABLE cp_candidates (
              id TEXT PRIMARY KEY, email TEXT UNIQUE NOT NULL, password_hash TEXT NOT NULL,
              profile TEXT NOT NULL, created_at TEXT NOT NULL, updated_at TEXT NOT NULL);
            CREATE TABLE cp_vacancies (
              id TEXT PRIMARY KEY, body TEXT NOT NULL, created_at TEXT NOT NULL);
            CREATE TABLE cp_applications (
              id TEXT PRIMARY KEY, candidate_id TEXT NOT NULL REFERENCES cp_candidates(id),
              vacancy_id TEXT NOT NULL REFERENCES cp_vacancies(id), status TEXT NOT NULL,
              approved_automatically INTEGER NOT NULL DEFAULT 0, created_at TEXT NOT NULL,
              decided_at TEXT, UNIQUE(candidate_id, vacancy_id));
            CREATE INDEX cp_application_candidate ON cp_applications(candidate_id);
            CREATE TABLE cp_meetings (
              id TEXT PRIMARY KEY, application_id TEXT UNIQUE NOT NULL REFERENCES cp_applications(id),
              start TEXT NOT NULL, end TEXT NOT NULL, status TEXT NOT NULL, room TEXT,
              confirmed_at TEXT, completed_at TEXT);
            CREATE TABLE em_workspaces (id TEXT PRIMARY KEY);
            CREATE TABLE cp_workflow_events (
              event_key TEXT PRIMARY KEY, candidate_id TEXT NOT NULL REFERENCES cp_candidates(id),
              application_id TEXT NOT NULL REFERENCES cp_applications(id),
              body TEXT NOT NULL, created_at TEXT NOT NULL);
            CREATE TABLE em_meeting_transcripts (
              meeting_id TEXT PRIMARY KEY REFERENCES cp_meetings(id),
              application_id TEXT NOT NULL REFERENCES cp_applications(id),
              transcript TEXT NOT NULL);
        ''')
        employer_workflow.init(self.db)
        employer_store.init(self.db)
        profile = json.dumps({'name': 'Migration fixture', 'consentReuse': True, 'autoApprove': False})
        self.db.execute('INSERT INTO cp_candidates VALUES (?,?,?,?,?,?)',
                        ('person-legacy', 'migration@example.test', 'fixture-password-hash', profile, STAMP, STAMP))
        self.db.execute('INSERT INTO cp_vacancies VALUES (?,?,?)',
                        ('vacancy-legacy', '{"id":"vacancy-legacy","title":"Fixture role"}', STAMP))
        self.db.execute('INSERT INTO cp_applications VALUES (?,?,?,?,?,?,?)',
                        ('application-legacy', 'person-legacy', 'vacancy-legacy', 'accepted', 1, STAMP, STAMP))
        self.db.execute('INSERT INTO cp_meetings VALUES (?,?,?,?,?,?,?,?)',
                        ('meeting-legacy', 'application-legacy', STAMP, '2026-10-13T10:30:00Z',
                         'completed', '{"id":"fixture-room","name":"fixture-room"}', STAMP, STAMP))
        self.db.execute("INSERT INTO em_workspaces VALUES ('workspace-legacy')")
        self.db.execute('''INSERT INTO em_reviews
            (application_id,workspace_id,state,queue_order,source,source_version,reason,created_at,updated_at)
            VALUES (?,?,'selected',1,'recruiter','legacy-fixture','Saved reason',?,?)''',
                        ('application-legacy', 'workspace-legacy', STAMP, STAMP))
        self.db.execute('''INSERT INTO cp_employer_workflows
            (application_id,revision,decision,after_interest,after_meeting_id,updated_at)
            VALUES (?,4,'pool','yes',?,?)''', ('application-legacy', 'meeting-legacy', STAMP))
        self.db.execute('''INSERT INTO cp_meeting_feedback
            (meeting_id,application_id,questionnaire,submitted,submitted_by,updated_at)
            VALUES (?,?,?,?,'fixture-manager',?)''',
                        ('meeting-legacy', 'application-legacy', '{"id":"questions-legacy"}',
                         '{"answers":{"q1":"Saved feedback"}}', STAMP))
        self.db.execute('''INSERT INTO cp_offer_versions
            (id,application_id,vacancy_id,version,terms,status,created_by,created_at,sent_at)
            VALUES (?,?,?,1,?,'sent','fixture-manager',?,?)''',
                        ('offer-legacy', 'application-legacy', 'vacancy-legacy', '{"role":"Saved offer"}', STAMP, STAMP))
        self.db.execute('''INSERT INTO cp_workflow_messages
            (id,application_id,actor,actor_id,text,created_at)
            VALUES (?,?,'candidate',?,'Saved message',?)''',
                        ('message-legacy', 'application-legacy', 'person-legacy', STAMP))
        self.db.execute('INSERT INTO cp_workflow_commands VALUES (?,?,?,?,?)',
                        ('application-legacy', 'candidate:person-legacy', 'request-legacy', 'fixture-fingerprint', STAMP))
        self.db.execute('INSERT INTO cp_workflow_events VALUES (?,?,?,?,?)',
                        ('event-legacy', 'person-legacy', 'application-legacy', '{"saved":true}', STAMP))
        self.db.execute('INSERT INTO em_meeting_transcripts VALUES (?,?,?)',
                        ('meeting-legacy', 'application-legacy', 'Saved transcript'))
        self.db.commit()

    def snapshot(self, tables=DEPENDENTS):
        return {table: self.db.execute('SELECT * FROM ' + table + ' ORDER BY 1').fetchall()
                for table in tables}

    def assert_integrity(self, *, foreign_keys=1):
        self.assertEqual(self.db.execute('PRAGMA foreign_keys').fetchone()[0], foreign_keys)
        self.assertEqual(self.db.execute('PRAGMA foreign_key_check').fetchall(), [])
        self.assertIsNone(self.db.execute(
            "SELECT name FROM sqlite_master WHERE type='table' AND name='cp_applications_next'").fetchone())
        for table in DEPENDENTS:
            targets = [row[2] for row in self.db.execute('PRAGMA foreign_key_list(' + table + ')')]
            self.assertNotIn('cp_applications_next', targets)

    def insert_application(self, application_id, *, candidate='person-legacy'):
        self.db.execute('''INSERT INTO cp_applications
            (id,candidate_id,vacancy_id,status,approved_automatically,created_at,decided_at)
            VALUES (?,?,?,'pending',0,?,NULL)''',
                        (application_id, candidate, 'vacancy-legacy', STAMP))

    def test_legacy_migration_preserves_all_identity_and_history_references(self):
        self.assertEqual(len(self.db.execute('PRAGMA table_info(cp_candidates)').fetchall()), 6)
        self.assertEqual(len(self.db.execute('PRAGMA table_info(cp_applications)').fetchall()), 7)
        original = self.snapshot(('cp_candidates', 'cp_applications', *DEPENDENTS))
        migrate_search(self.db)
        self.assertEqual(self.snapshot(), {table: original[table] for table in DEPENDENTS})
        self.assertEqual(self.db.execute('''SELECT id,email,password_hash,profile,created_at,updated_at
            FROM cp_candidates ORDER BY id''').fetchall(), original['cp_candidates'])
        self.assertEqual(self.db.execute('''SELECT id,candidate_id,vacancy_id,status,
            approved_automatically,created_at,decided_at FROM cp_applications ORDER BY id''').fetchall(),
                         original['cp_applications'])
        self.assertEqual(self.db.execute('SELECT searching FROM cp_candidates').fetchall(), [(1,)])
        self.assertEqual(self.db.execute('SELECT archived_at FROM cp_applications').fetchall(), [(None,)])
        self.assert_integrity()
        self.db.commit()
        with sqlite3.connect(self.path) as reopened:
            self.assertEqual(reopened.execute('PRAGMA foreign_key_check').fetchall(), [])
            self.assertEqual(reopened.execute('SELECT application_id FROM em_meeting_transcripts').fetchone(),
                             ('application-legacy',))

    def test_archived_pair_allows_a_new_application_but_never_two_active_ones(self):
        with self.assertRaises(sqlite3.IntegrityError):
            self.insert_application('before-migration')
        self.db.rollback()
        migrate_search(self.db)
        self.db.execute('UPDATE cp_applications SET archived_at=? WHERE id=?', (STAMP, 'application-legacy'))
        self.insert_application('application-second')
        with self.assertRaises(sqlite3.IntegrityError):
            self.insert_application('application-third')
        self.assertEqual(self.db.execute('SELECT id,archived_at FROM cp_applications ORDER BY id').fetchall(),
                         [('application-legacy', STAMP), ('application-second', None)])
        self.assertEqual(self.db.execute('SELECT application_id FROM cp_meetings').fetchone(),
                         ('application-legacy',))
        self.assert_integrity()

    def test_repeat_migration_preserves_paused_state_and_archived_period(self):
        migrate_search(self.db)
        self.db.execute('UPDATE cp_candidates SET searching=0')
        self.db.execute('UPDATE cp_applications SET archived_at=?', (STAMP,))
        self.db.commit()
        previous = self.snapshot(('cp_candidates', 'cp_applications', *DEPENDENTS))
        migrate_search(self.db)
        self.assertEqual(self.snapshot(('cp_candidates', 'cp_applications', *DEPENDENTS)), previous)
        self.assert_integrity()

    def test_full_portal_init_twice_migrates_legacy_relations_without_resetting_search(self):
        portal = object.__new__(CandidatePortal)
        portal.notifications = None
        original = self.snapshot(tuple(table for table in DEPENDENTS if table != 'cp_meetings'))
        portal.init(self.db)
        self.db.execute('UPDATE cp_candidates SET searching=0')
        self.db.execute('UPDATE cp_applications SET archived_at=?', (STAMP,))
        self.db.commit()
        portal.init(self.db)
        self.assertEqual(self.snapshot(tuple(original)), original)
        self.assertEqual(self.db.execute('SELECT id,application_id,status FROM cp_meetings').fetchone(),
                         ('meeting-legacy', 'application-legacy', 'completed'))
        self.assertEqual(self.db.execute('SELECT searching FROM cp_candidates').fetchone(), (0,))
        self.assertEqual(self.db.execute('SELECT archived_at FROM cp_applications').fetchone(), (STAMP,))
        prepared = candidate_invites.create_prepared(self.db, {'consentReuse': False, 'autoApprove': False})
        self.assertEqual(self.db.execute('SELECT email,searching FROM cp_candidates WHERE id=?', (prepared,)).fetchone(),
                         (None, 1))
        self.assert_integrity()

    def test_migration_restores_disabled_foreign_keys_and_keeps_constraints(self):
        self.db.execute('PRAGMA foreign_keys=OFF')
        migrate_search(self.db)
        self.assert_integrity(foreign_keys=0)
        self.db.execute('PRAGMA foreign_keys=ON')
        with self.assertRaises(sqlite3.IntegrityError):
            self.insert_application('orphan-application', candidate='missing-person')
        self.db.rollback()
        with self.assertRaises(sqlite3.IntegrityError):
            self.db.execute('UPDATE cp_candidates SET searching=2')


if __name__ == '__main__':
    unittest.main()
