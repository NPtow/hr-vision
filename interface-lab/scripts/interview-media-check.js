// Playwright CLI run-code. The technical video is local QA material, never published.
async (page) => {
  const checks = [], errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const assert = (pass, name) => { if (!pass) throw new Error(name); checks.push(name); };
  const fixture = '/Users/NIKITA/Documents/ChatGPT/HR Vision/tmp/interview-test/technical-playback.mp4';
  await page.setViewportSize({ width:1440, height:1000 });
  await page.getByRole('button', { name:'Вариант 01: Список и профиль', exact:true }).click();
  await page.locator('.hpa-person-row').first().click();
  assert(await page.locator('.hpa-split-detail .ir-media-missing').isVisible(), 'Absent recording has explicit state');
  await page.locator('.hpa-split-detail .ir-chapters button').first().click();
  assert((await page.locator('.hpa-split-detail .ir-seek-status').innerText()).includes('Видеозапись не подключена'), 'Missing media does not claim playback');
  await page.locator('.ir-lab-media summary').click();
  await page.getByLabel('Локальный видеофайл', {exact:true}).setInputFiles(fixture);
  const video = page.locator('.hpa-split-detail video');
  await video.evaluate(v => v.readyState >= 1 ? undefined : new Promise((resolve,reject) => { v.addEventListener('loadedmetadata',resolve,{once:true}); v.addEventListener('error',reject,{once:true}); }));
  assert(await video.evaluate(v => v.duration >= 740), 'Real HTML video loads metadata');
  assert((await page.locator('.hpa-split-detail .ir-local-source').innerText()).includes('может не совпадать'), 'Technical media is not represented as candidate evidence');
  await video.evaluate(v => v.play());
  await page.waitForFunction(() => document.querySelector('.hpa-split-detail video')?.currentTime > .1);
  assert(await video.evaluate(v => !v.paused && v.currentTime > 0), 'Native playback advances actual video time');
  await video.evaluate(v => v.pause());
  await page.locator('.hpa-split-detail .ir-chapters button').nth(1).click();
  assert(await video.evaluate(v => Math.abs(v.currentTime - 695) < .5), 'Chapter 11:35 seeks to 695 seconds');
  assert(await page.locator('.hpa-split-detail .ir-chapters button').nth(1).getAttribute('aria-current') === 'true', 'Current chapter tracks video position');
  await page.locator('.hpa-split-detail').getByRole('button',{name:'Полное интервью',exact:true}).click();
  assert(await video.evaluate(v => Math.abs(v.currentTime - 695) < .5), 'Short to full preserves playback position');
  await video.evaluate(v => { v.currentTime = 270; v.dispatchEvent(new Event('timeupdate')); });
  await page.waitForFunction(() => document.querySelector('.hpa-split-detail .ir-chapters button')?.getAttribute('aria-pressed') === 'true');
  assert(await page.locator('.hpa-split-detail .ir-chapters button').first().getAttribute('aria-pressed') === 'true', 'Scrubbing selects matching chapter');
  await page.locator('.hpa-split-detail .hpa-evidence').nth(1).click();
  const modalVideo = page.getByRole('dialog').locator('video');
  await page.waitForFunction(() => Math.abs(document.querySelector('[role="dialog"] video')?.currentTime - 695) < .5);
  assert(await modalVideo.evaluate(v => v.paused), 'Direct fragment seeks without autoplay');
  await video.evaluate(v => v.play());
  await modalVideo.evaluate(v => v.play());
  assert(await video.evaluate(v => v.paused), 'Starting second player pauses first');
  await page.keyboard.press('Escape');
  assert(await page.getByRole('dialog').count() === 0, 'Video dialog dismisses');
  await page.locator('.hpa-person-row').nth(1).click();
  assert(await page.locator('.hpa-split-detail .ir-media-missing').isVisible(), 'Video does not leak to another candidate');
  await page.getByRole('combobox',{name:'Карточка для проверки',exact:true}).selectOption('mikhail');
  await page.getByLabel('Локальный видеофайл',{exact:true}).setInputFiles(fixture);
  await page.waitForFunction(() => document.querySelector('.hpa-split-detail video')?.readyState >= 1);
  await page.locator('.hpa-split-detail .ir-chapters button').first().click();
  assert(await video.evaluate(v => Math.abs(v.currentTime - 370) < .5), 'Other candidate chapter seeks to 06:10');
  await page.locator('.hpa-person-row').first().click();
  assert(await video.count() === 1, 'Previously attached candidate keeps its own media');
  await page.getByRole('button',{name:'Сбросить локальные файлы',exact:true}).click();
  assert(await page.locator('video').count() === 0, 'Reset removes all local media');
  // The fixture below is deliberately not a valid container, to exercise decoder failure.
  await page.getByRole('combobox',{name:'Карточка для проверки',exact:true}).selectOption('anna');
  await page.getByLabel('Локальный видеофайл',{exact:true}).setInputFiles({name:'broken.mp4',mimeType:'video/mp4',buffer:Buffer.from('not a video')});
  await page.locator('.hpa-split-detail .ir-media-error').waitFor();
  assert((await page.locator('.hpa-split-detail .ir-media-error').innerText()).includes('Не удалось открыть'), 'Unavailable recording has visible recoverable error');
  await page.getByRole('button',{name:'Сбросить локальные файлы',exact:true}).click();
  assert(await page.locator('.hpa-split-detail .ir-media-missing').isVisible(), 'Reset recovers from decoder error');
  assert(errors.length === 0, `No page errors: ${errors.join('; ')}`);
  return {passed:checks.length,checks,errors};
}
