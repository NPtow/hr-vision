// Run with playwright-cli run-code on either published or local manager story.
async (page) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  const checks = [];
  const assert = (value, message) => { if (!value) throw new Error(message); checks.push(message); };
  const role = name => page.getByRole('group', { name: 'Посмотреть интерфейс' }).getByRole('button', { name, exact: true }).click();
  const stored = () => page.evaluate(() => JSON.parse(localStorage.getItem('hr-vision-agency-preview-v1')).state);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await role('Нанимающий');
  await page.getByRole('button', { name: 'Сбросить пример', exact: true }).click();
  await page.getByRole('heading', { name: 'Первая подборка 3' }).waitFor();
  assert(await page.getByRole('button', { name: /^Открыть:/ }).count() === 3, 'Three prepared candidates');
  await page.getByRole('textbox', { name: 'Найти кандидата' }).fill('Неизвестный');
  assert(await page.getByText('Нет кандидатов', { exact: true }).isVisible(), 'Empty search explains recovery');
  await page.getByRole('button', { name: 'Сбросить фильтры' }).click();
  await page.locator('.ag-evidence > button').first().click();
  await page.getByRole('dialog').waitFor();
  assert((await page.getByRole('dialog').innerText()).includes('не запись реального интервью'), 'Evidence source and demo boundary visible');
  await page.keyboard.press('Escape');
  assert(await page.getByRole('dialog').count() === 0, 'Dialog closes with Escape');
  await page.getByRole('button', { name: 'Не подходит', exact: true }).click();
  await page.getByRole('button', { name: 'Сохранить решение', exact: true }).click();
  assert(await page.getByRole('alert').isVisible(), 'Decline requires reason');
  await page.getByLabel('Причина', { exact: true }).fill('Нужен другой отраслевой опыт');
  await page.getByRole('button', { name: 'Сохранить решение', exact: true }).click();
  assert((await stored()).decisions.anna.kind === 'decline', 'Manager decline saved');
  await page.getByRole('button', { name: 'Вернуть к рассмотрению', exact: true }).click();
  await page.getByRole('button', { name: 'Задать вопрос', exact: true }).click();
  await page.getByLabel('Ваш вопрос', { exact: true }).fill('Когда согласуем KPI роли?');
  await page.getByRole('button', { name: 'Сохранить вопрос', exact: true }).click();
  assert((await stored()).coordinatorQuestion === 'Когда согласуем KPI роли?' && !(await stored()).decisions.anna.question, 'Coordinator question is separate from person');

  await role('Кандидат');
  await page.getByRole('button', { name: 'Мне интересно', exact: true }).click();
  await page.getByRole('tab', { name: 'Следующий шаг' }).click();
  assert(await page.getByRole('heading', { name: 'Ваш интерес отмечен', exact: true }).isVisible(), 'Candidate interest waits for manager independently');
  assert(await page.getByRole('radio').count() === 0, 'Cannot book without manager invitation');
  await page.getByRole('tab', { name: 'Мой профиль' }).click();
  await page.getByLabel('Имя и фамилия', { exact: true }).fill('');
  await page.getByRole('button', { name: 'Сохранить профиль', exact: true }).click();
  assert(await page.getByText('Укажите имя, чтобы к вам можно было обратиться.').isVisible(), 'Profile validates before save');
  await page.getByLabel('Имя и фамилия', { exact: true }).fill('Анна Миронова');
  await page.getByLabel('Ожидания по доходу', { exact: true }).fill('175 000 ₽ на руки + бонус');
  await page.getByRole('button', { name: 'Сохранить профиль', exact: true }).click();
  await role('Нанимающий');
  await page.getByRole('tab', { name: 'Условия', exact: true }).click();
  assert(!(await page.locator('.ag-facts').innerText()).includes('175 000'), 'Unshared profile update stays private');
  await role('Кандидат');
  await page.getByRole('tab', { name: 'Мой профиль' }).click();
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Сохранить профиль', exact: true }).click();
  await page.getByRole('button', { name: 'Хочу поговорить с рекрутером', exact: true }).click();
  assert((await stored()).candidateInterview === 'hr-requested', 'Human interview request recorded without invented completion');
  await role('Нанимающий');
  await page.getByRole('tab', { name: 'Условия', exact: true }).click();
  assert((await page.locator('.ag-facts').innerText()).includes('175 000'), 'Consented profile update visible to manager');
  await page.getByRole('button', { name: 'Пригласить на встречу', exact: true }).click();
  assert((await stored()).candidateReply === 'pending', 'Invitation does not confirm a meeting');
  await role('Кандидат');
  await page.getByRole('tab', { name: 'Следующий шаг' }).click();
  assert(await page.getByRole('radio').count() === 3, 'Slots visible after mutual interest');
  assert(await page.getByRole('button', { name: 'Подтвердить время', exact: true }).isDisabled(), 'Booking requires explicit slot');
  await page.getByRole('radio').first().focus();
  await page.keyboard.press('ArrowRight');
  assert(await page.getByRole('radio').nth(1).getAttribute('aria-checked') === 'true', 'Slots support arrow-key selection');
  await page.getByRole('button', { name: 'Подтвердить время', exact: true }).click();
  assert((await stored()).candidateReply === 'confirmed', 'Candidate independently confirms offered slot');
  await role('Нанимающий');
  assert((await page.locator('.ag-decision').innerText()).includes('Встреча согласована'), 'Manager sees reciprocal confirmation');
  await page.reload();
  await page.locator('.ag-decision').waitFor();
  assert((await page.locator('.ag-decision').innerText()).includes('Встреча согласована'), 'State survives reload');
  await role('Кандидат');
  await page.getByRole('tab', { name: 'Следующий шаг' }).click();
  await page.getByRole('button', { name: 'Нужно другое время', exact: true }).click();
  await page.getByLabel('Ваши варианты', { exact: true }).fill('9 октября после 14:00 МСК');
  await page.getByRole('button', { name: 'Сохранить варианты', exact: true }).click();
  await page.getByLabel('Что хотели бы уточнить до встречи?', { exact: true }).fill('Как устроен бонус?');
  await page.getByRole('button', { name: 'Сохранить вопрос', exact: true }).click();
  assert((await stored()).candidateTimeRequest === '9 октября после 14:00 МСК' && (await stored()).candidateQuestion === 'Как устроен бонус?', 'Question does not overwrite reschedule request');
  await page.getByRole('tab', { name: 'Предложение', exact: true }).click();
  await page.getByRole('button', { name: 'Роль больше не интересна' }).click();
  await page.getByRole('button', { name: 'Отказаться от этой роли' }).click();
  assert((await stored()).candidateInterest === 'declined' && !(await stored()).meetingSlot, 'Candidate decline cancels booking');
  await role('Нанимающий');
  assert((await page.locator('.ag-decision').innerText()).includes('Кандидат отказался'), 'Manager sees candidate refusal');
  await page.getByRole('button', { name: 'Вернуть к рассмотрению', exact: true }).click();
  assert((await stored()).candidateInterest === 'declined', 'Manager cannot overwrite candidate interest');

  await page.getByRole('button', { name: 'Сбросить пример', exact: true }).click();
  for (const width of [1440, 1024, 768, 390]) {
    await page.setViewportSize({ width, height: 1000 });
    await role('Нанимающий');
    const checkOverflow = async label => assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `${label} fits ${width}px`);
    await checkOverflow('Manager shortlist');
    await page.getByRole('button', { name: 'Открыть: Михаил Белов', exact: true }).click();
    await checkOverflow('Manager detail');
    assert(await page.getByRole('button', { name: 'Пригласить на встречу', exact: true }).isVisible(), `Manager action available at ${width}px`);
    if (width === 390) await page.getByRole('button', { name: 'К подборке', exact: true }).click();
    await role('Кандидат');
    await checkOverflow('Candidate offer');
    await page.getByRole('tab', { name: 'Мой профиль', exact: true }).click();
    await checkOverflow('Candidate profile');
    await page.getByRole('tab', { name: 'Следующий шаг' }).click();
    await checkOverflow('Candidate next step');
  }
  await page.setViewportSize({ width: 1440, height: 1000 });
  await role('Нанимающий');
  await page.getByRole('button', { name: 'Сбросить пример', exact: true }).click();
  assert(errors.length === 0, `No page errors: ${errors.join('; ')}`);
  return { passed: checks.length, checks, errors };
}
