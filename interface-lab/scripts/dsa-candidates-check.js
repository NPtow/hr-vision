// Public deployment + read-only source. Never reset the hiring scenario.
// Materialize the private invitation into an ignored temporary copy.
async page => {
  const key = __PRIVATE_INVITATION__;
  const site = 'https://hr-vision.158-160-179-53.sslip.io';
  const start = site + '/iframe.html?id=hr-vision-product--start&viewMode=story';
  const checks = [], errors = [], videos = [];
  const assert = (value, name) => { if (!value) throw new Error(name); checks.push(name); };
  page.on('pageerror', e => errors.push(e.message));
  const unauthorized = await page.request.get(site + '/api/hr/dsa-candidates');
  assert(unauthorized.status() === 401, 'No anonymous access to candidate data');
  await page.goto(start + '#team=' + encodeURIComponent(key));
  await page.getByRole('button', { name: /Войти работодателем/ }).click();
  await page.getByRole('button', { name: 'Открыть кандидатов ДСА', exact: true }).waitFor();
  const token = await page.evaluate(() => sessionStorage.getItem('hr-vision-connected-session'));
  const auth = { Authorization: 'Bearer ' + token };
  const before = await (await page.request.get(site + '/api/hr/state', { headers: auth })).json();
  const source = await (await page.request.get(site + '/api/hr/dsa-candidates', { headers: auth })).json();
  assert(source.candidates.length === 6, 'All six source profiles connected');
  await page.getByRole('button', { name: 'Открыть кандидатов ДСА', exact: true }).click();
  await page.locator('.dsa-shortlist .cj-person').first().waitFor();
  assert(await page.locator('.dsa-shortlist .cj-person').count() === 6, 'Six visible candidate cards');
  for (let i = 0; i < source.candidates.length; i++) {
    const c = source.candidates[i];
    await page.locator('.dsa-shortlist .cj-person').nth(i).click();
    await page.getByRole('heading', { name: c.name, exact: true }).waitFor();
    const video = page.locator('.dsa-profile video');
    await video.waitFor();
    await page.waitForFunction(() => document.querySelector('.dsa-profile video')?.readyState >= 1, { timeout: 25000 });
    const duration = await video.evaluate(v => v.duration);
    videos.push({ index: i + 1, metadataLoaded: true, duration: Math.round(duration) });
    assert(Number.isFinite(duration) && duration > 60, 'Candidate ' + (i + 1) + ': real video metadata');
    assert(await page.locator('.ir-chapters li').count() === c.shortChapters.length, 'Candidate ' + (i + 1) + ': original short cuts');
    await page.locator('.ir-chapters button').nth(1).click();
    await page.waitForFunction(expected => Math.abs(document.querySelector('.dsa-profile video').currentTime - expected) < 1, c.shortChapters[1].seconds);
    assert(true, 'Candidate ' + (i + 1) + ': timestamp seeks real video');
    await video.evaluate(v => { v.muted = true; return v.play(); });
    const selectedTime = c.shortChapters[1].seconds;
    await page.waitForFunction(expected => document.querySelector('.dsa-profile video').currentTime > expected + .2, selectedTime, { timeout: 20000 });
    await video.evaluate(v => v.pause());
    assert(true, 'Candidate ' + (i + 1) + ': playback advances');
    await page.getByRole('button', { name: 'Полное интервью', exact: true }).click();
    assert(await page.locator('.ir-chapters li').count() === c.fullChapters.length, 'Candidate ' + (i + 1) + ': full chapter list');
    await page.locator('.ir-chapters button').nth(1).click();
    await page.waitForFunction(expected => Math.abs(document.querySelector('.dsa-profile video').currentTime - expected) < 1, c.fullChapters[1].seconds);
    assert(await page.locator('.ir-excerpt blockquote').count() === 0, 'Candidate ' + (i + 1) + ': chapter summary is not a fabricated quote');
    await page.getByRole('tab', { name: 'Профиль', exact: true }).click();
    assert(await page.locator('.dsa-facts > div').count() === c.profile.length, 'Candidate ' + (i + 1) + ': source profile fields');
    await page.getByRole('tab', { name: 'Резюме', exact: true }).click();
    assert((await page.locator('.dsa-cv').textContent()) === c.cv, 'Candidate ' + (i + 1) + ': original CV');
    await page.getByRole('tab', { name: 'Интервью', exact: true }).click();
  }
  await page.locator('.dsa-shortlist .cj-person').first().click();
  const c = source.candidates[0];
  const video = page.locator('.dsa-profile video');
  await page.waitForFunction(() => document.querySelector('.dsa-profile video')?.readyState >= 1);
  await page.locator('.ir-chapters button').first().click();
  await video.evaluate(v => { v.muted = true; return v.play(); });
  await video.evaluate((v, end) => { v.currentTime = end - .15; }, c.shortChapters[0].endSeconds);
  await page.waitForFunction(expected => { const v = document.querySelector('.dsa-profile video'); return v.currentTime >= expected && v.currentTime < expected + 5; }, c.shortChapters[1].seconds, { timeout: 20000 });
  await video.evaluate(v => v.pause());
  assert(true, 'Short version automatically advances across source cuts');
  await page.screenshot({ path: 'output/playwright/dsa-candidates-private/desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), '390px detail has no horizontal overflow');
  await page.screenshot({ path: 'output/playwright/dsa-candidates-private/mobile-detail.png', fullPage: true });
  await page.getByRole('button', { name: 'К кандидатам', exact: true }).click();
  await page.screenshot({ path: 'output/playwright/dsa-candidates-private/mobile-list.png', fullPage: true });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), '390px list has no horizontal overflow');
  await page.getByRole('button', { name: 'Задачи найма', exact: true }).click();
  assert(await page.getByRole('button', { name: 'Открыть подборку', exact: true }).isVisible(), 'Existing test task remains accessible');
  await page.getByRole('button', { name: 'HR Vision.', exact: true }).click();
  await page.getByRole('button', { name: /Войти кандидатом/ }).first().click();
  await page.locator('.cj-account').waitFor();
  const candidateToken = await page.evaluate(() => sessionStorage.getItem('hr-vision-connected-session'));
  assert((await page.request.get(site + '/api/hr/dsa-candidates', { headers: { Authorization: 'Bearer ' + candidateToken } })).status() === 403, 'Candidate role cannot read employer materials');
  const after = await (await page.request.get(site + '/api/hr/state', { headers: auth })).json();
  assert(JSON.stringify(before) === JSON.stringify(after), 'Hiring state preserved byte for byte');
  assert(errors.length === 0, 'No JavaScript errors');
  return { checks, videos, errors, revision: after.revision };
}
