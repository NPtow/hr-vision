import assert from 'node:assert/strict';
import { groupTranscriptTurns, parseMeetingTranscript, transcriptInRange } from '../src/scenes/connected-journey/transcript.ts';

const daily = parseMeetingTranscript('WEBVTT\n\ntranscript:1\n00:00:06.178 --> 00:00:09.578\n<v>Анна:</v>Работала с клиентами.\n');
assert.equal(daily[0].title, 'Анна');
assert.equal(daily[0].fragment, 'Работала с клиентами.');
assert.equal(daily[0].seconds, 6.178);
assert.equal(daily[0].endSeconds, 9.578);
assert.equal(daily[0].speaker, 'Анна');
const standard = parseMeetingTranscript('WEBVTT\n\n00:02.000 --> 00:04.000\n<v Иван>Вопрос &amp; пример</v>\n');
assert.equal(standard[0].title, 'Иван');
assert.equal(standard[0].fragment, 'Вопрос & пример');
assert.equal(standard[0].seconds, 2);
assert.equal(parseMeetingTranscript('WEBVTT\n').length, 0);
assert.equal(parseMeetingTranscript('Обычный текст без таймкодов.').length, 0);
assert.equal(parseMeetingTranscript('00:70.000 --> 00:71.000\nОшибочное время').length, 0);
assert.equal(parseMeetingTranscript('00:04.000 --> 00:02.000\nОбратный диапазон').length, 0);
assert.equal(parseMeetingTranscript('WEBVTT\n\nNOTE an ignored cue\n00:02.000 --> 00:04.000\nnot speech').length, 0);

const dsa = parseMeetingTranscript(`# Synthetic fixture in the source DSA format, no personal data\n[00:02-00:09] Р: Расскажите о задаче.\n[00:09-00:12] К: Первый ответ.\n[00:12-00:12] К: Уточнение.\n[00:12-00:16] Р: Что было дальше?\n[00:16-00:19] К: Следующий ответ.\n[00:19-00:19] К: Точка после фрагмента.\n[01:02:03-01:02:04] Р: Часовой таймкод.\n`);
assert.equal(dsa.length, 7);
assert.equal(dsa[0].speaker, 'Рекрутер');
assert.equal(dsa[1].speaker, 'Кандидат');
assert.equal(dsa[1].fragment, 'Первый ответ.');
assert.equal(dsa[2].seconds, 12);
assert.equal(dsa[2].endSeconds, 12);
assert.equal(dsa[6].seconds, 3723);
assert.deepEqual(transcriptInRange(dsa, 12, 19).map(cue => cue.fragment), ['Уточнение.', 'Что было дальше?', 'Следующий ответ.']);
assert.deepEqual(transcriptInRange(dsa, 9, 12).map(cue => cue.fragment), ['Первый ответ.']);
assert.deepEqual(transcriptInRange(dsa, 11, 13).map(cue => cue.fragment), ['Первый ответ.', 'Уточнение.', 'Что было дальше?']);
assert.equal(transcriptInRange(dsa, 12, 12).length, 0);
assert.equal(transcriptInRange(dsa, Number.NaN, 19).length, 0);
assert.equal(transcriptInRange(daily, 9.578, 10).length, 0);
assert.equal(transcriptInRange(daily, 7, 9).length, 1);
assert.equal(transcriptInRange(dsa, 3723, null)[0].fragment, 'Часовой таймкод.');
assert.equal(parseMeetingTranscript('[00:70-00:71] Р: Неверное время.').length, 0);
assert.equal(parseMeetingTranscript('[00:10-00:09] К: Обратный диапазон.').length, 0);
assert.equal(parseMeetingTranscript('[00:09-00:10] ?: Неизвестный формат говорящего.').length, 0);
assert.equal(parseMeetingTranscript('[00:09-00:10] Р:  ').length, 0);
assert.equal(parseMeetingTranscript('[00:09-00:10] Р: Точная речь.\nНепривязанный текст.')[0].fragment, 'Точная речь.');
assert.equal(parseMeetingTranscript('WEBVTT\n\n00:00:01.000 --> 00:00:02.000\n<v Кандидат>[00:09-00:10] Р: Это произнесённый текст.</v>')[0].seconds, 1);
const turns = groupTranscriptTurns(dsa);
assert.equal(turns.length, 5);
assert.deepEqual(turns[1], { speaker: 'Кандидат', fragments: ['Первый ответ.', 'Уточнение.'] });
assert.deepEqual(turns.flatMap(turn => turn.fragments), dsa.map(cue => cue.fragment));
assert.equal(dsa[1].fragment, 'Первый ответ.');
assert.equal(groupTranscriptTurns([{ ...dsa[0], speaker: undefined }, { ...dsa[1], speaker: undefined }]).length, 2);
console.log('39 transcript checks passed: VTT/DSA ranges, point cues, adjacent speakers grouped without changing speech.');
