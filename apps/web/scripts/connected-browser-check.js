// Only run on the shared test before handoff. The script changes fixture accounts.
async page => {
  const teamKey = __TEAM_JSON__;
  const url = 'https://hr-vision.158-160-179-53.sslip.io/iframe.html?id=hr-vision-product--start&viewMode=story';
  const checks=[]; const errors=[];
  const assert=(v,label)=>{if(!v)throw new Error(label);checks.push(label)};
  const button=(p,name)=>p.getByRole('button',{name,exact:true});
  const nav=(p,name)=>p.getByRole('navigation',{name:'Этапы найма'}).getByRole('button',{name,exact:true});
  const open=async(p,actor)=>{
    p.on('pageerror',e=>errors.push(e.message));
    await p.goto(url);
    await p.evaluate(key=>sessionStorage.setItem('hr-vision-team',key),teamKey);
    await p.reload();
    await p.getByRole('button').filter({has:p.getByRole('heading',{name:actor,exact:true})}).click();
  };
  const browser=page.context().browser();
  const ca=await browser.newContext({viewport:{width:1440,height:1000}});
  const cm=await browser.newContext({viewport:{width:1440,height:1000}});
  const anna=await ca.newPage(); const mikhail=await cm.newPage();
  await page.setViewportSize({width:1440,height:1000});
  await open(page,'Иван Петров');
  await page.locator('.cj-test-footer summary').click();
  await button(page,'Начать заново').click();
  await button(page,'Сбросить тест').click();
  await button(page,'Открыть подборку').click();
  await page.getByRole('heading',{name:'Пока нет подтверждённых кандидатов'}).waitFor();
  assert(true,'Employer starts without unaccepted candidates');
  await open(anna,'Анна Миронова');
  await button(anna,'Мне интересно').click();
  await page.getByRole('button',{name:/Анна Миронова/}).first().waitFor();
  assert(true,'Acceptance in another browser adds candidate to employer');
  await button(page,'Выбрать время встречи').click();
  await page.getByRole('radio').first().click();
  await button(page,'Предложить встречу').click();
  await page.getByText('Ждём подтверждения кандидата',{exact:true}).waitFor();
  assert(!await button(page,'Войти в видеовстречу').count(),'Employer cannot enter pending meeting');
  await nav(anna,'Встреча').click();
  await button(anna,'Подтвердить встречу').click();
  await page.getByText('Подтверждена',{exact:true}).waitFor();
  assert(await button(page,'Войти в видеовстречу').count()===1,'Candidate confirmation unlocks employer room');
  await open(mikhail,'Михаил Белов');
  await mikhail.locator('.cj-auto > summary').click();
  await mikhail.getByRole('checkbox',{name:'Принимать подходящие вакансии автоматически'}).check();
  await nav(page,'Подборка · 2').click();
  await page.getByRole('button',{name:/Михаил Белов/}).first().click();
  await button(page,'Выбрать время встречи').click();
  await page.getByRole('radio').first().click();
  await button(page,'Предложить встречу').click();
  await nav(mikhail,'Встреча').click();
  await button(mikhail,'Подтвердить встречу').waitFor();
  assert(true,'Auto vacancy acceptance retains manual meeting confirmation');
  await button(mikhail,'Подтвердить встречу').click();
  await nav(page,'Встречи · 2').click();
  assert(await page.locator('.cj-main .cj-list-row').count()===2,'Both meetings are visible together');
  for(const width of [1440,390]){
    await page.setViewportSize({width,height:1000});
    await page.screenshot({path:`output/playwright/connected-meetings-${width}.png`,fullPage:true});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),`Meetings fit ${width}px`);
  }
  await page.setViewportSize({width:1440,height:1000});
  await page.reload();
  // Start story deliberately opens the account picker on reload; server state remains.
  await page.getByRole('button').filter({has:page.getByRole('heading',{name:'Иван Петров',exact:true})}).click();
  await button(page,'Открыть подборку').click();
  await nav(page,'Встречи · 2').click();
  assert(await page.locator('.cj-main .cj-list-row').count()===2,'Two meetings survive reload and relogin');
  await page.getByRole('button',{name:/Анна Миронова/}).first().click();
  await nav(anna,'Чат').click();
  await anna.getByRole('textbox',{name:'Сообщение',exact:true}).fill('Как устроен бонус?');
  await button(anna,'Отправить').click();
  await nav(page,'Чат').click();
  await page.getByText('Как устроен бонус?',{exact:true}).waitFor();
  assert(true,'Candidate chat message arrives in employer account');
  await page.getByRole('textbox',{name:'Сообщение',exact:true}).fill('Бонус рассчитывается по повторным продажам.');
  await button(page,'Отправить').click();
  await anna.getByText('Бонус рассчитывается по повторным продажам.',{exact:true}).waitFor();
  assert(true,'Employer reply arrives in candidate account');
  await nav(page,'Встречи · 2').click();
  await page.getByRole('button',{name:/Анна Миронова/}).first().click();
  await page.locator('.cj-test-controls > summary').click();
  await button(page,'Пропустить звонок в тесте').click();
  await page.getByRole('heading',{name:'Как прошла встреча?',exact:true}).waitFor();
  for(const [i,value] of ['Показала кейс возврата клиента','Нужно проверить вклад','Запросить рекомендацию'].entries()) await page.locator('.cj-feedback textarea').nth(i).fill(value);
  await button(page,'Сохранить фидбек').click();
  await page.getByRole('heading',{name:'Разбор встречи',exact:true}).waitFor();
  assert(true,'Completed test meeting requires feedback before assessment');
  await nav(anna,'Встреча').click();
  await button(anna,'Хочу продолжить').click();
  await page.getByText('Кандидат хочет продолжить',{exact:true}).waitFor();
  await button(page,'Добавить в пул для оффера').click();
  await page.getByRole('button',{name:/Анна Миронова/}).first().click();
  const future=new Date(Date.now()+14*86400000).toISOString().slice(0,10);
  await page.getByLabel('Предполагаемая дата выхода',{exact:true}).fill(future);
  await button(page,'Сохранить условия').click();
  await button(page,'Отправить оффер').click();
  await nav(anna,'Оффер').click();
  await button(anna,'Обсудить условия').click();
  await anna.getByRole('textbox',{name:'Сообщение',exact:true}).fill('Можем обсудить дату выхода?');
  await button(anna,'Отправить').click();
  await nav(anna,'Оффер').click();
  await button(anna,'Принять оффер').click();
  await page.getByText('Анна Миронова принял(а) оффер. Подбор завершён.',{exact:true}).waitFor();
  assert(true,'Offer travels to candidate and acceptance closes employer hiring');
  assert(!await button(page,'Отправить оффер').count(),'No more offers after acceptance');
  await anna.screenshot({path:'output/playwright/connected-offer-1440.png',fullPage:true});
  await anna.setViewportSize({width:390,height:1000});
  assert(await anna.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Candidate offer fits 390px');
  await anna.screenshot({path:'output/playwright/connected-offer-390.png',fullPage:true});
  await page.locator('.cj-test-footer summary').click();
  await button(page,'Начать заново').click();
  await button(page,'Сбросить тест').click();
  await button(page,'Открыть подборку').click();
  await page.getByRole('heading',{name:'Пока нет подтверждённых кандидатов'}).waitFor();
  assert(true,'Shared reset restores initial state');
  await button(page,'HR Vision.').click();
  await page.screenshot({path:'output/playwright/connected-start-1440.png',fullPage:true});
  assert(errors.length===0,'No browser runtime errors');
  await ca.close(); await cm.close();
  return {status:'passed',count:checks.length,checks,errors};
}
